#!/usr/bin/env python3
"""Generate res.cpp from JSON resource files.

Usage:
    python3 gen_res.py <res_dir> <namespace> <output_path>

Example:
    python3 gen_res.py res/ core src/core/res.cpp

Key convention:
    - Files directly in res/<namespace>/ -> key is just filename (e.g. "io.json")
    - Files in subdirectories like res/<namespace>/xxx/a.json -> key is "xxx/a.json"
    - A .md file is converted to the block model by md2js.py and embedded under the
      same stem with a .json key (lang.md -> "lang.json"), compact on the wire
"""
import sys
import os
import json
import glob

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import md2js


def compact_json(content):
    """Remove whitespace from JSON, preserving string content."""
    try:
        obj = json.loads(content)
        return json.dumps(obj, separators=(',', ':'), ensure_ascii=False)
    except json.JSONDecodeError:
        return content.strip()


def sanitize_var_name(name):
    """Convert filename to valid C++ variable name."""
    return name.replace('/', '__').replace('.', '_').replace('-', '_')


def main():
    if len(sys.argv) != 4:
        print(f"Usage: {sys.argv[0]} <res_dir> <namespace> <output_path>", file=sys.stderr)
        sys.exit(1)

    res_dir = sys.argv[1]
    namespace = sys.argv[2]
    output_path = sys.argv[3]

    os.makedirs(os.path.dirname(output_path) or '.', exist_ok=True)

    files = sorted(glob.glob(os.path.join(res_dir, '**', '*.json'), recursive=True) +
                   glob.glob(os.path.join(res_dir, '**', '*.md'), recursive=True))

    if not files:
        print(f"Warning: No resource files found in {res_dir}", file=sys.stderr)

    lines = []
    lines.append(f'// Auto-generated by gen_res.py')
    lines.append(f'#include "res.h"')
    lines.append(f'#include <unordered_map>')
    lines.append(f'')

    entries = []
    seen = set()

    for path in files:
        rel_path = os.path.relpath(path, res_dir)
        parts = rel_path.replace(os.sep, '/').split('/')
        if len(parts) >= 2:
            key = '/'.join(parts[1:])
        else:
            key = parts[0]

        with open(path, 'r', encoding='utf-8') as f:
            content = f.read()
        if path.endswith('.md'):
            key = os.path.splitext(key)[0] + '.json'
            try:
                compacted = md2js.to_json(content, compact=True, source=path)
            except md2js.LangError as e:
                print(e, file=sys.stderr)
                sys.exit(1)
        else:
            compacted = compact_json(content)

        if key in seen:
            print(f"Duplicate resource key: {key}", file=sys.stderr)
            sys.exit(1)
        seen.add(key)

        var_name = f'{namespace}__{sanitize_var_name(key)}'
        entries.append((var_name, key, compacted))

    for var_name, key, compacted in entries:
        lines.append(f'static const char* {var_name} = R"RES({compacted})RES";')

    lines.append(f'')

    map_name = f'{namespace}_res_map'
    lines.append(f'static const std::unordered_map<std::string, const char*> {map_name} = {{')

    for var_name, key, _ in entries:
        lines.append(f'    {{"{key}", {var_name}}},')

    lines.append(f'}};')
    lines.append(f'')

    lines.append(f'namespace {namespace} {{')
    lines.append(f'    const char* get_res(const std::string& name) {{')
    lines.append(f'        auto it = {map_name}.find(name);')
    lines.append(f'        return it != {map_name}.end() ? it->second : nullptr;')
    lines.append(f'    }}')
    lines.append(f'}}')
    lines.append(f'')

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))

    print(f'Generated {output_path} with {len(entries)} resources')


if __name__ == '__main__':
    main()
